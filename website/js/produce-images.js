    /**
     * Get suggestions based on typed name
     * @param {string} name - The search query
     * @returns {Array<{name: string, url: string}>} Array of matching suggestions
     */
    getSuggestions(name) {
        if (!name || name.trim().length === 0) return [];
        
        const query = name.toLowerCase().trim();
        const matches = [];

        for (const [cropName, url] of Object.entries(this.stockImages)) {
            if (cropName.includes(query)) {
                matches.push({ name: cropName, url });
            }
        }

        return matches.slice(0, 5); // Return top 5 matches
    }
